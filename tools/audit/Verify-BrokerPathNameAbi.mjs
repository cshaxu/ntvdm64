import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
const root=process.cwd(), build=path.resolve('build/M0-T412/S2/path-abi');
fs.mkdirSync(build,{recursive:true});
const env=path.join(build,'msvc.cmd');
fs.writeFileSync(env,'@echo off\r\nset "path_abi_cwd=%CD%"\r\ncall "C:\\Program Files (x86)\\Microsoft Visual Studio\\2022\\BuildTools\\Common7\\Tools\\VsDevCmd.bat" -arch=x86 -host_arch=x64 >nul\r\nif errorlevel 1 exit /b %errorlevel%\r\ncd /d "%path_abi_cwd%"\r\n%*\r\n');
const log=fs.openSync(path.join(build,'build.log'),'w');
const compile=spawnSync('cmd.exe',['/d','/c',`call "${env}" cl.exe /nologo /MT /W4 "${root}/tests/broker/path_name_abi.c" /Fepath-abi.exe /Fopath-abi.obj /link ntdll.lib`],{cwd:build,windowsHide:true,windowsVerbatimArguments:true,stdio:['ignore',log,log],timeout:60000});
fs.closeSync(log);
assert.equal(compile.status,0,'See build.log');
const exe=path.join(build,'path-abi.exe'), image=fs.readFileSync(exe);
assert.equal(image.readUInt16LE(image.readUInt32LE(0x3c)+4),0x14c);
const inputPaths=['MEM.EXE','COMMAND.COM','EDIT.COM','system32/WRITE.EXE'];
const inputs=()=>inputPaths.map(name=>{const bytes=fs.readFileSync(path.join('O:/ntvdm64',name)); return {name,size:bytes.length,sha256:createHash('sha256').update(bytes).digest('hex')};});
const before=inputs();
const run=spawnSync(exe,[],{cwd:'O:/ntvdm64',windowsHide:true,encoding:'utf8',timeout:10000});
assert.deepEqual(inputs(),before,'Read-only image probe changed input bytes');
fs.writeFileSync(path.join(build,'result.json'),JSON.stringify({inputs:before,status:run.status,stdout:run.stdout,stderr:run.stderr,error:run.error?.message},null,2));
console.log(run.stdout,run.stderr);
assert.equal(run.status,0,'Path ABI assertion failed');
